import assert from 'node:assert/strict';
import { observationScore, sightBlocked, visibleAnimal } from '../src/systems/observation.js';
const eye = { x: 0, y: 2, z: 0 }, forward = { x: 0, y: 0, z: -1 };
const field = { sample: () => 0 };
const ahead = { x: 0, y: 2, z: -8 };
assert(Number.isFinite(observationScore(eye, forward, ahead, 20, [], field)));
assert.equal(observationScore(eye, forward, { ...ahead, z: 8 }, 20, [], field), Infinity);
assert.equal(observationScore(eye, forward, ahead, 5, [], field), Infinity);
const wall = [{ x: 0, z: -4, hw: 2, hd: 0.3, rot: 0 }];
assert(sightBlocked(eye, ahead, wall, field));
const house = [{ ...wall[0], minY: 0, maxY: 4 }];
assert(sightBlocked(eye, ahead, house, field), '屋身挡住视线');
assert(!sightBlocked({ ...eye, y: 8 }, { ...ahead, y: 8 }, house, field), '越过屋顶的视线不应被无限高墙挡住');
assert(sightBlocked({ ...eye, y: 8 }, { ...ahead, y: 0 }, house, field), '斜视线与屋身相交时仍遮挡');
assert.equal(observationScore(eye, forward, ahead, 20, wall, field), Infinity);
const hill = { sample: (x, z) => z < -3 && z > -5 ? 3 : 0 };
assert(sightBlocked(eye, ahead, [], hill));
const dog = { ...ahead, kind: 'dog', name: '犬' };
assert.equal(visibleAnimal(dog, eye, forward, 20, [], field).id, 'dog');
assert.equal(visibleAnimal(dog, eye, forward, 20, [], hill), null, '动物被山坡遮挡时不能记录');
assert.equal(visibleAnimal({ ...dog, z: 8 }, eye, forward, 20, [], field), null, '转身后不能记录旧目标');
assert(Number.isFinite(observationScore(eye, forward, { x: 3, y: 2, z: -8 }, 20, [], field)));
console.log('observation checks passed');
